"""Derive typed, marshalled Session methods from the pinned public C header."""
import json,re,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def signatures():
 s=(ROOT/'upstream/swephexp.h').read_text()
 s=re.sub(r'/\*.*?\*/','',s,flags=re.S);s=re.sub(r'//[^\n]*','',s)
 result=[]
 for ret,name,args in re.findall(r'ext_def\s*\(\s*([^()]*)\s*\)\s*(swe_\w+)\s*\((.*?)\)\s*;',s,re.S):
  params=[]
  for i,param in enumerate(args.split(',')):
   param=' '.join(param.split())
   if param=='void':continue
   match=re.fullmatch(r'(const )?(char|double|int32|int|centisec|CSEC|AS_BOOL)\s*(\*)?\s*(\w+)?',param)
   if not match:raise ValueError((name,param))
   const,typ,ptr,pname=match.groups();pname=pname or 'buffer'
   if pname in ['type','range','map','func','go','var','s','f','err','result']:pname+='Value'
   p={'name':pname,'ctype':typ,'pointer':bool(ptr),'const':bool(const)}
   if ptr:
    if typ=='char' and const:p.update(gotype='string',size=230 if name=='swe_set_ephe_path' else 255)
    elif typ=='char':p.update(gotype='[]byte',size=8192 if pname=='sdet' else 256)
    elif typ=='double':p.update(gotype='[]float64',size=double_size(name,pname))
    else:p.update(gotype='[]int32',size=1)
   else:p['gotype']='float64' if typ=='double' else ('int8' if typ=='char' else 'int32')
   params.append(p)
  ret=' '.join(ret.split());rtype='string' if '*' in ret else ('float64' if ret=='double' else ('void' if ret=='void' else 'int32'))
  result.append({'c_name':name,'go_name':''.join(p.title() for p in name[4:].split('_')),'return':rtype,'params':params})
 return result

def double_size(f,n):
 if n=='geopos':return 10 if f in ['swe_sol_eclipse_where','swe_lun_occult_where'] else 3
 common={'dgeo':3,'datm':4,'dobs':6,'xx':6,'xxret':6,'darr':50,'cusps':37,'ascmc':10,'cusp_speed':37,'ascmc_speed':10,'xpin':2,'attr':20,'xaz':3,'xin':3,'xout':3,'xnasc':6,'xndsc':6,'xperi':6,'xaphe':6}
 if n in common:return common[n]
 if n in ['xpo','xpn']:return 6 if f=='swe_cotrans_sp' else 3
 if n=='tret':return 1 if f.startswith('swe_rise_trans') else 10
 if n=='dret':return {'swe_heliacal_ut':50,'swe_vis_limit_mag':8,'swe_heliacal_angle':3,'swe_topo_arcus_visionis':1,'swe_utc_to_jd':2,'swe_refrac_extended':4,'swe_get_orbital_elements':50}[f]
 return 1

def generate():
 apis=signatures()
 code=['// Code generated by tools/generate_api.py; DO NOT EDIT.','// SPDX-License-Identifier: AGPL-3.0-only','package swisseph','import ("github.com/ruqingxu001/swisseph-go/internal/raw"; "modernc.org/libc")']
 for a in apis:
  ret=a['return'];isvoid=ret=='void';result='(err error)' if isvoid else f'(result {ret}, err error)'
  args=', '.join(p['name']+' '+p['gotype'] for p in a['params'])
  sizes=', '.join(f"{p['name']} >= {p['size']}" for p in a['params'] if p['pointer'] and not p['const'])
  code.append(f"// {a['go_name']} calls {a['c_name']}. "+('Buffer lengths: '+sizes+'.' if sizes else ''))
  code.append('// C status/diagnostic outputs retain their original meaning; err reports Go ABI validation only.')
  code.append(f"func (s *Session) {a['go_name']}({args}) {result} {{")
  code.append('if err=s.enter();err!=nil{return};defer s.mu.Unlock();f:=frame{tls:s.c.tls};defer f.close()')
  callargs=['s.c.tls']
  for p in a['params']:
   n=p['name']
   if not p['pointer']:
    if p['gotype']=='float64':code.append(f'if !finite({n}){{err=invalidNumber("{n}");return}}')
    callargs.append(f'abiChar({n})' if p['ctype']=='char' else n);continue
   method={'string':'text','[]byte':'bytes','[]float64':'doubles','[]int32':'ints'}[p['gotype']]
   code.append(f'p_{n}:=f.{method}("{n}",{n},{p["size"]})');callargs.append('p_'+n)
  code.append('if f.err!=nil{err=f.err;return}')
  rawcall=f"raw.X{a['c_name']}({','.join(callargs)})"
  if isvoid:code.append(rawcall)
  elif ret=='string':code.append(f'result=libc.GoString({rawcall})')
  else:code.append('result='+rawcall)
  code.append('f.copyBack();return\n}')
 (ROOT/'api_generated.go').write_text('\n'.join(code)+'\n')
 (ROOT/'api.json').write_text(json.dumps(apis,indent=2)+'\n')
 subprocess.run(['gofmt','-w',str(ROOT/'api_generated.go')],check=True)
 print('Generated',len(apis),'public API methods')
if __name__=='__main__':generate()
