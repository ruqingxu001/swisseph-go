"""Reproduce the Go translation; upstream sources are never modified."""
import argparse
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCES = 'swedate swehouse swejpl swemmoon swemplan sweph swephlib swecl swehel'.split()
TARGETS = ['darwin/amd64', 'darwin/arm64', 'linux/amd64', 'linux/arm64']

def verify():
    for line in (ROOT/'upstream/SHA256SUMS').read_text().splitlines():
        digest, name = line.split('  ')
        if hashlib.sha256((ROOT/'upstream'/name).read_bytes()).hexdigest() != digest:
            raise SystemExit('Upstream checksum mismatch: ' + name)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('targets', nargs='*', metavar='OS/ARCH', help=', '.join(TARGETS))
    args = parser.parse_args()
    for target in args.targets:
        if target not in TARGETS:
            parser.error('unsupported target: ' + target)
    verify()
    env = dict(os.environ)
    env['GOPROXY'] = os.environ.get('SWISSGO_GOPROXY', 'https://proxy.golang.org,direct')
    subprocess.run(['go', 'mod', 'download'], cwd=ROOT, env=env, check=True)
    with tempfile.TemporaryDirectory(prefix='swisseph-translate-') as tmp:
        temp = Path(tmp)
        shutil.copytree(ROOT/'upstream', temp/'upstream')
        for name in ['go.mod', 'go.sum']:
            shutil.copyfile(ROOT/name, temp/name)
        # Supported targets use 64-bit long and file offsets. Only JPL I/O names
        # change, because libc v1 lacks Darwin fseeko/ftello. Headers stay intact.
        jpl = temp/'upstream/swejpl.c'
        s = jpl.read_text()
        assert s.count('#define FSEEK fseeko') == 1
        assert s.count('#define FTELL ftello') == 1
        jpl.write_text(s.replace('#define FSEEK fseeko', '#define FSEEK fseek')
                       .replace('#define FTELL ftello', '#define FTELL ftell'))
        for target in args.targets or TARGETS:
            goos, goarch = target.split('/')
            output = temp/f'swe_{goos}_{goarch}.go'
            cmd = ['go','run','modernc.org/ccgo/v4@v4.26.0',
                   '--goos',goos,'--goarch',goarch,
                   '-DTLSOFF','-DNO_SWE_GLP','-Iupstream',
                   '--package-name','raw','--prefix-external','X','-o',output.name]
            cmd += [f'upstream/{n}.c' for n in SOURCES]
            print('Translating',target,flush=True)
            subprocess.run(cmd,cwd=temp,env=env,check=True)
            notice = ('// Derived from Swiss Ephemeris 2.10.03; AGPL-3.0.\n'
                      '// See upstream/LICENSE, LICENSE, and NOTICE.md.\n'
                      '// Generated by tools/generate.py; do not edit.\n\n')
            dest = ROOT/'internal/raw'/output.name
            dest.parent.mkdir(parents=True,exist_ok=True)
            dest.write_text(notice+(ROOT/'upstream/LICENSE').read_text()+'\n'+output.read_text().replace('libc.Xatof(', 'cAtof('))
            subprocess.run(['gofmt','-w',str(dest)],check=True)
            print('Wrote',dest.name,flush=True)

if __name__ == '__main__':
    main()
